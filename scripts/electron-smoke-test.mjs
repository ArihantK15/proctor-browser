import { existsSync, readFileSync } from 'node:fs'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const { INVITE_REGEX } = require('../config.js')
const { extractInviteToken } = require('../lib/utils.js')

const requiredFiles = [
  'main.js',
  'preload.js',
  'lobby_preload.js',
  'setup-preload.js',
  'renderer/index.html',
  'app/static/student.html',
  'app/static/theme.css',
  'app/static/_safe.js',
  'app/static/student-app.js',
  'proctor.py',
  'behavioral_analysis.py',
  'audio_processor.py',
  'frame_buffer.py',
  'scripts/download_audio_models.py',
  'requirements-proctor.txt',
  'config.js',
]

const missing = requiredFiles.filter((path) => !existsSync(path))
if (missing.length) {
  throw new Error(`Missing Electron runtime files: ${missing.join(', ')}`)
}

const pkg = JSON.parse(readFileSync('package.json', 'utf8'))
const files = pkg.build?.files || []
if (!pkg.build?.appId) throw new Error('Electron build.appId is missing')
if (!files.includes('renderer/**/*')) throw new Error('Electron build.files must include renderer/**/*')
if (!files.includes('app/static/student.html')) throw new Error('Electron build.files must include the student shell')
if (!files.includes('app/static/_safe.js')) throw new Error('Electron build.files must include _safe.js for the lobby')
if (!files.includes('app/static/student-app.js')) throw new Error('Electron build.files must include student-app.js for the lobby')
if (!pkg.build?.mac || !pkg.build?.win) {
  throw new Error('Electron mac/win build targets are missing')
}
if (!pkg.build?.electronFuses) {
  throw new Error('Electron fuses block is missing — security hardening regressed')
}

// PIP_PACKAGES ⊇ requirements-proctor.txt guard. A package listed in
// requirements but NOT in PIP_PACKAGES means a student install diverges
// from the documented dev install — exactly the bug we hit when vosk +
// python_speech_features were added to requirements-proctor.txt and
// the student installer kept omitting them.
const configJs = readFileSync('config.js', 'utf8')
const pipMatch = configJs.match(/const PIP_PACKAGES = \[([\s\S]*?)\]/)
if (!pipMatch) {
  throw new Error('PIP_PACKAGES not found in config.js — student installer will install nothing')
}
// Strip JS line-comments BEFORE splitting on commas, otherwise a
// pattern like "// note\n  'vosk'," lands in the same fragment and
// our package-name parser thinks the whole fragment is a comment.
const pipBody = pipMatch[1].replace(/\/\/[^\n]*/g, '')
// Match each quoted spec, then strip the version (specs can contain commas,
// e.g. 'opencv-python>=4.13.0.92,<5', so a naive split(',') would shred them).
const pipPkgs = new Set(
  [...pipBody.matchAll(/['"]([^'"]+)['"]/g)]
    .map(m => m[1].split(/[<>=!~,]/)[0].trim().toLowerCase().replace(/_/g, '-'))
    .filter(Boolean)
)
const reqLines = readFileSync('requirements-proctor.txt', 'utf8').split('\n')
const reqPkgs = reqLines
  .map(l => l.trim())
  .filter(l => l && !l.startsWith('#'))
  .map(l => l.split(/[<>=!~,]/)[0].trim().toLowerCase().replace(/_/g, '-'))
const missingFromInstaller = reqPkgs.filter(p => !pipPkgs.has(p))
if (missingFromInstaller.length) {
  throw new Error(
    `PIP_PACKAGES is missing ${missingFromInstaller.join(', ')} — student installer will diverge ` +
    `from requirements-proctor.txt. Add these to config.js#PIP_PACKAGES.`
  )
}

// The invite handoff is the highest-risk Electron lobby path:
// email -> browser invite page -> procta:// deep link -> lobby accept -> exam list.
// Keep accepting the canonical URL plus query-param variants generated by
// browsers or future landing pages, but reject malformed/short tokens.
const inviteToken = 'abcDEF12_x'
const inviteCases = [
  `procta://invite/${inviteToken}`,
  `procta://invite/${inviteToken}/`,
  `procta://invite?token=${inviteToken}`,
  `procta://open?invite=${inviteToken}`,
]
for (const inviteUrl of inviteCases) {
  const parsed = extractInviteToken(inviteUrl, INVITE_REGEX)
  if (parsed !== inviteToken) {
    throw new Error(`Invite deep-link parser failed for ${inviteUrl}: got ${parsed || 'null'}`)
  }
}
for (const badInviteUrl of ['procta://invite/short', 'procta://invite/../../bad']) {
  const parsed = extractInviteToken(badInviteUrl, INVITE_REGEX)
  if (parsed) {
    throw new Error(`Invite deep-link parser accepted malformed token from ${badInviteUrl}`)
  }
}

// bundle-python.js (the BUILD-TIME installer) must install exactly the
// canonical set. It used to keep its own hand-maintained PACKAGES array that
// silently drifted from config.js — shipping mediapipe/scipy (unused) while
// omitting uniface/vosk/python_speech_features/websocket-client/psutil, so a
// freshly built app failed checkPackagesReady and fell into a nondeterministic
// first-launch pip. We now require it to (a) import PIP_PACKAGES from config
// and (b) install that very list directly (spread/map into the pip call), so
// the three lists (bundle-python ⊇ config ⊇ requirements) can never diverge.
const bundleJs = readFileSync('bundle-python.js', 'utf8')
if (!/const\s+\{\s*PIP_PACKAGES\s*\}\s*=\s*require\(['"]\.\/config['"]\)/.test(bundleJs)) {
  throw new Error(
    'bundle-python.js must import PIP_PACKAGES from ./config (single source of truth) — ' +
    'found no `const { PIP_PACKAGES } = require(\'./config\')`.'
  )
}
// Must actually USE PIP_PACKAGES to install (mac: `...PIP_PACKAGES` /
// `PIP_PACKAGES.map`; win: `...PIP_PACKAGES`), not import-then-ignore it.
if (!/\.\.\.PIP_PACKAGES|PIP_PACKAGES\.(map|join)\b/.test(bundleJs)) {
  throw new Error(
    'bundle-python.js imports PIP_PACKAGES but never installs it (no `...PIP_PACKAGES` ' +
    'spread or `PIP_PACKAGES.map(...)` in a pip call) — the bake would ship the wrong set.'
  )
}
if (/const\s+PACKAGES\s*=\s*\[/.test(bundleJs)) {
  throw new Error(
    'bundle-python.js declares a literal PACKAGES array — remove it and install ' +
    'config.js#PIP_PACKAGES directly so the build-time installer cannot drift.'
  )
}

console.log('Electron smoke test passed')
